// BUSCAR TASA PARA UNA FECHA DADA
// ============================================
// Acepta 'YYYY-MM-DD' o 'DD/MM/YYYY'
// Si es fin de semana o feriado, usa el día hábil anterior
function buscarTasaEnHistoricoLocal(fecha) {
    if (!fecha) return null;
    
    // Normalizar a YYYY-MM-DD
    let fechaISO = fecha;
    if (fecha.includes('/')) {
        const partes = fecha.split('/');
        if (partes.length === 3) {
            fechaISO = `${partes[2]}-${partes[1].padStart(2,'0')}-${partes[0].padStart(2,'0')}`;
        }
    }
    
    // Buscar exacta
    if (TASAS_BCV_HISTORICO[fechaISO]) {
        return TASAS_BCV_HISTORICO[fechaISO];
    }
    
    // Buscar hacia atrás (máximo 5 días)
    const date = new Date(fechaISO + 'T00:00:00');
    for (let i = 1; i <= 5; i++) {
        date.setDate(date.getDate() - 1);
        const key = date.toISOString().split('T')[0];
        if (TASAS_BCV_HISTORICO[key]) {
            console.log(`⚠️ ${fechaISO} no tiene tasa, usando ${key}`);
            return TASAS_BCV_HISTORICO[key];
        }
    }
    
    return null;
}

